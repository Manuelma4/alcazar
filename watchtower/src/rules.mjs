/** @type {ReadonlyMap<string, Readonly<RuleMeta>>} */
export const RULES_BY_ID = new Map(RULES.map((rule) => [rule.id, rule]));

/** Severities from most to least severe. */
export const SEVERITIES = Object.freeze(['critical', 'high', 'medium', 'low', 'info']);

/**
 * Numeric rank of a severity (critical = 4 ... info = 0, unknown = -1).
 * @param {string} severity
 * @returns {number}
 */
export function severityRank(severity) {
  const index = SEVERITIES.indexOf(/** @type {Severity} */ (severity));
  return index === -1 ? -1 : SEVERITIES.length - 1 - index;
}
