/**
 * Rule catalogue. The order of RULES is part of the public contract (SARIF
 * `ruleIndex` points into it), so new rules are appended per language block
 * and never reordered.
 */

/** @typedef {'critical'|'high'|'medium'|'low'|'info'} Severity */

/**
 * @typedef {object} RuleMeta
 * @property {string} id
 * @property {string} name        PascalCase name used in SARIF
 * @property {string} title
 * @property {Severity} severity  default severity (a finding may override it)
 * @property {string} cwe         e.g. 'CWE-470'
 * @property {'cobol'|'fortran'|'any'} language
 * @property {'high'|'medium'|'low'} precision
 * @property {string} summary
 * @property {string} rationale
 * @property {string} fix
 * @property {string} docs        repository-relative path of the rule page
 */

/**
 * @param {Omit<RuleMeta, 'docs'>} rule
 * @returns {Readonly<RuleMeta>}
 */
function defineRule(rule) {
  return Object.freeze({ ...rule, docs: `docs/rules/${rule.id}.md` });
}

