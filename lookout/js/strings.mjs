const PLACEHOLDER = /\{(\w+)(?:\|([^|{}]*)\|([^{}]*))?\}/g;

function fill(template, params) {
  return template.replace(PLACEHOLDER, (_match, name, one, other) => {
    const value = params?.[name];
    if (one !== undefined) {
      const n = typeof value === 'number' ? value : Number(String(value ?? '').replace(/[^\d.-]/g, ''));
      return n === 1 ? one : other;
    }
    return value === undefined || value === null ? '' : String(value);
  });
}

/**
 * Look up a UI string. Unknown keys return the key itself (and the test
 * suite fails), so a missing string is visible rather than silent.
 */
export function t(key, params) {
  const template = Object.hasOwn(STRINGS, key) ? STRINGS[key] : key;
  return params ? fill(template, params) : template.replace(PLACEHOLDER, (m, name, one, other) => (one !== undefined ? other : m));
}

t.has = (key) => Object.hasOwn(STRINGS, key);
